// build-skill.mjs — builds scripts/witness-mutation-gate.mjs, the single-file Agensi skill script, from the
// witness v0.6 git tag, pinned by SHA-256.
//
// Agensi runs a skill script on its own, from a temporary file, where it cannot see any other file of the
// package; v0.6 is two files (witness.mjs starts runner.mjs as its supervisor). So the bundle carries
// runner.mjs's code as a function and starts ITSELF as the supervisor. Every change to v0.6 is mechanical,
// asserted to apply exactly once, and listed in the script's header. bundle.test.mjs then runs v0.6's own
// test suite against the bundle in a folder with no runner.mjs.
//
//   node build-skill.mjs           write scripts/witness-mutation-gate.mjs and LICENSE
//   node build-skill.mjs --check   exit 1 if either differs from what the v0.6 tag + this folder produce (CI)
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';

const TAG = 'v0.6';
const PIN = {
  'witness.mjs': '9918297aa5f8fc4e1d26d9e6b25226f56102fdc04f0c634155bfcba1c086ef48',
  'runner.mjs': 'e85f13b1b30c40c045bcb7997a5d73808c14684dcd161c4a2ea14caaf47c3a0e',
};
const OUT = 'scripts/witness-mutation-gate.mjs';
const sha = (b) => createHash('sha256').update(b).digest('hex');

function fromTag(path) {
  const buf = execFileSync('git', ['show', `${TAG}:${path}`], { maxBuffer: 1 << 26 });
  if (sha(buf) !== PIN[path]) throw new Error(`${TAG}:${path} does not match its pinned SHA-256`);
  return buf.toString('utf8');
}

function replaceOnce(text, from, to) {
  const i = text.indexOf(from);
  if (i === -1 || text.indexOf(from, i + 1) !== -1) throw new Error('expected exactly one occurrence of: ' + from.slice(0, 90));
  return text.slice(0, i) + to + text.slice(i + from.length);
}

// Replace "estate" with "project" on comment lines only, asserting the exact number of lines touched and
// that no code line contains the word (so the code itself stays byte-identical to v0.6).
function commentWording(code, expectedLines) {
  let touched = 0;
  const out = code.split('\n').map((line) => {
    if (!/\b[Ee]state\b/.test(line)) return line;
    if (!/^\s*\/\//.test(line)) throw new Error('"estate" outside a comment line: ' + line.trim().slice(0, 90));
    touched++;
    return line.replace(/\bestate\b/g, 'project').replace(/\bEstate\b/g, 'Project');
  });
  if (touched !== expectedLines) throw new Error(`expected ${expectedLines} comment lines with "estate", found ${touched}`);
  return out.join('\n');
}

function stripImports(code, from) {
  return code.split('\n').filter((l) => !l.startsWith('import ') || !l.includes(from)).join('\n');
}

function bundle(witness, runner, kernel, cli) {
  let w = witness.replace(/\r\n/g, '\n');
  w = replaceOnce(w, "const RUNNER = join(dirname(fileURLToPath(import.meta.url)), 'runner.mjs');",
    "const RUNNER = fileURLToPath(import.meta.url);   // skill bundle: this file is also the supervisor (RUNNER MODE below)");
  w = replaceOnce(w, '[RUNNER, String(timeout), ...testCmd]', "[RUNNER, '--witness-runner', String(timeout), ...testCmd]");
  w = replaceOnce(w, "import { spawnSync } from 'node:child_process';", "import { spawn, spawnSync } from 'node:child_process';");
  w = replaceOnce(w, 'if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {\n  main();\n}\n', '');

  const r = runner.replace(/\r\n/g, '\n');
  const argvLine = 'const [, , boundArg, ...cmd] = process.argv;';
  let runnerBody = replaceOnce(r.slice(r.indexOf(argvLine)), argvLine,
    'const [, , , boundArg, ...cmd] = process.argv;   // argv[2] is --witness-runner');

  // 5. v0.6's comments use an in-house word for the author's repositories; in comments only it reads "project".
  w = commentWording(w, 8);
  runnerBody = commentWording(runnerBody, 0);

  return [
    '#!/usr/bin/env node',
    '// witness-mutation-gate — the Agensi skill script, generated by skill/build-skill.mjs in the sjgant80-hub/witness',
    `// repository from the witness ${TAG} tag: witness.mjs (sha256 ${PIN['witness.mjs'].slice(0, 16)}…) and runner.mjs`,
    `// (sha256 ${PIN['runner.mjs'].slice(0, 16)}…), joined into one file because a skill script runs on its own.`,
    '// The changes to v0.6, all mechanical:',
    '//   1. RUNNER is this file. witness starts it with --witness-runner, and it then runs runner.mjs\'s code (RUNNER MODE).',
    '//   2. child_process also imports spawn, which runner.mjs needs.',
    '//   3. v0.6\'s entry guard is replaced by the DISPATCH at the end of the file, which compares real paths.',
    '//   4. Added: the `receipt` command (RECEIPT LAYER + RECEIPT MODE). It runs the same gate as `mutate`.',
    '//   5. In comments only, the in-house word for the author\'s repositories now reads "project".',
    '// What it does on your machine: it edits the source file it gates, one mutant at a time, and always restores it',
    '// (a sidecar backup recovers a killed run); it runs the test command you give it. It makes no network calls.',
    '// MIT licence.',
    '',
    '// ======== witness v0.6: witness.mjs ========',
    w.trimEnd(),
    '',
    '// ======== RUNNER MODE: witness v0.6 runner.mjs, as a function ========',
    'function runnerMode() {',
    runnerBody.trimEnd(),
    '}',
    '',
    '// ======== RECEIPT LAYER: skill/kernel.mjs (mutation-gated on its own) ========',
    kernel.trimEnd(),
    '',
    '// ======== RECEIPT MODE: skill/cli-receipt.mjs ========',
    stripImports(cli, "'./kernel.mjs'").trimEnd(),
    '',
    '// ======== DISPATCH ========',
    '// v0.6 started main() only when argv[1] matched import.meta.url. Node resolves the module URL to the REAL path but',
    '// leaves argv[1] as typed, so the comparison fails whenever the script is reached through a symlink (on macOS /tmp',
    '// and the system temp folder are symlinks), and a skill script always runs from a temporary file: main() would',
    '// never run, and the process would exit 0 having gated nothing. Compare real paths on both sides instead. Imported',
    '// as a library (v0.6\'s own tests do this), it is not the entry point and runs nothing.',
    "import { realpathSync } from 'node:fs';",
    `const ENGINE_SHA256 = '${PIN['witness.mjs']}';`,
    'function isEntryPoint() {',
    '  if (!process.argv[1]) return false;',
    '  try { return realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url)); }',
    '  catch { return import.meta.url === pathToFileURL(process.argv[1]).href; }',
    '}',
    'if (isEntryPoint()) {',
    "  if (process.argv[2] === '--witness-runner') runnerMode();",
    "  else if (process.argv[2] === 'receipt') receiptMode(process.argv.slice(2));",
    '  else main();',
    '}',
    '',
  ].join('\n');
}

const outputs = [
  [OUT, bundle(fromTag('witness.mjs'), fromTag('runner.mjs'), readFileSync('kernel.mjs', 'utf8'), readFileSync('cli-receipt.mjs', 'utf8'))],
  ['LICENSE', readFileSync('../LICENSE', 'utf8')],
];
if (process.argv.includes('--check')) {
  let drift = 0;
  for (const [path, want] of outputs) {
    const have = existsSync(path) ? readFileSync(path, 'utf8') : null;
    if (have !== want) { console.error(`✗ ${path} is out of date: run node build-skill.mjs`); drift++; }
    else console.log(`✓ ${path} matches the ${TAG} tag and this folder`);
  }
  process.exit(drift ? 1 : 0);
}
mkdirSync('scripts', { recursive: true });
for (const [path, text] of outputs) { writeFileSync(path, text); console.log(`wrote ${path} (${Buffer.byteLength(text)} bytes)`); }
